def get_locale(code: str | None) -> str:
    if not code:
        return DEFAULT_LOCALE
    code = str(code).lower().replace("_", "-")
    if code in AVAILABLE_LOCALES:
        return code
    base = code.split("-", 1)[0]
    if base in AVAILABLE_LOCALES:
        return base
    return DEFAULT_LOCALE


def load_catalog(locale: str | None = None) -> dict[str, str]:
    loc = get_locale(locale)
    out: dict[str, str] = {}
    for key, variants in _STRINGS.items():
        out[key] = variants.get(loc) or variants.get(DEFAULT_LOCALE) or key
    return out


def translate(key: str, locale: str | None = None, **kwargs: Any) -> str:
    loc = get_locale(locale)
    variants = _STRINGS.get(key) or {}
    text = variants.get(loc) or variants.get(DEFAULT_LOCALE) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError, IndexError):
            return text
    return text
